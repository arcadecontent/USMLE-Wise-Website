/**
 * SAMPLE data for the Conference Finder page (/conference-finder).
 *
 * One-time snapshot taken from the team's "US Conference Master" tracking
 * sheet so the page can be reviewed with real-looking content. This is NOT
 * live data and will go stale -- wiring this page up to the CRM (the same way
 * data/rotations.php pulls from team.manikmadaan.com) is a follow-up dev task.
 *
 * Field notes:
 * - start_date / end_date / deadline_date are ISO (YYYY-MM-DD), parsed from
 *   the sheet's date columns. The finder computes "X days left" from these
 *   at render time (see usmlewise_conf_days_until() in conference-finder.php)
 *   so the counters stay correct instead of going stale like a baked-in
 *   number would.
 * - deadline_open / deadline_label are derived from the sheet's free-text
 *   "Abstract submission deadline" column (closed / not-verified / not-an-
 *   abstract-venue text vs. an actual dated deadline). deadline_date is only
 *   set for the ~11 conferences with a real published date (the sheet's
 *   "Live deadlines" tab); the rest are null and render as TBD.
 * - registration_deadline_date: not tracked anywhere in the source sheet
 *   yet (it only has a generic info/registration link, not a date). Always
 *   null for now -- renders as "Stay tuned". Needs a new column in the
 *   tracking sheet before this can be real.
 * - submission_fee: almost never stated in the sheet's notes (2 of 105
 *   rows). Set by hand for the one conference with a clear dollar figure;
 *   null (renders "TBD") everywhere else.
 * - publishes_abstract: not tracked as a structured field anywhere in the
 *   sheet. Always null for now -- renders as "TBD". Needs the research
 *   manager to classify this per conference (e.g. Yes / No / Not stated).
 * - usmlewise_participating: true when USMLE Wise is attending/exhibiting at
 *   the conference. Not in the source sheet either, so every row ships false
 *   until the team confirms which ones we are at; flip the ones we attend to
 *   true and the card picks up the "USMLE Wise attending" badge and matches
 *   the sidebar's "USMLE Wise attending" filter. Use null (not false) if a
 *   conference is under consideration but unconfirmed -- that renders as
 *   "To be confirmed" instead of "Not attending".
 * - There is no poster/oral/both field in the source sheet yet, so it is not
 *   rendered here.
 * - specialty_value is a single, often fellowship-level tag straight from the
 *   sheet. The sidebar groups those under the specialty you actually apply to
 *   in the Match -- see usmlewise_conference_specialty_groups() below.
 */

/**
 * Specialty taxonomy for the sidebar filter.
 *
 * The sheet tags each conference at whatever level the organising society
 * sits at, so a flat list put Cardiology, Nephrology and Rheumatology beside
 * Internal Medicine as if they were peers -- 29 options, most of them IM
 * fellowships. This maps each leaf onto its parent Match specialty: parents
 * are what the sidebar lists, and a parent with more than one child gets a
 * caret that reveals its subspecialties for people who do want to narrow.
 *
 * Keys are the parent (filter) value; 'children' are specialty_value leaves.
 * Every leaf in the sample's 'specialties' list must appear in exactly one
 * group -- usmlewise_render_conf_specialty_filter() appends any stray leaf as
 * its own row rather than silently dropping it from the filter.
 *
 * Grouping notes: critical care and pulm/crit sit under Internal Medicine
 * because that's the usual route in, even though EM, anaesthesia and surgery
 * also fellow into it. Neurosurgery, Orthopaedics, Otolaryngology, Urology
 * and Ophthalmology stay top-level rather than folding into a "Surgery"
 * umbrella, since each is its own categorical Match specialty.
 */
