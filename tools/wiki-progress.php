<?php
/**
 * Wiki progress tracker. Compares the master plan (data/wiki-plan.php) with the
 * Markdown actually on disk, so progress is computed, never hand-maintained.
 *
 *     php tools/wiki-progress.php              summary by phase and section
 *     php tools/wiki-progress.php --todo       the next unstarted pages, by phase
 *     php tools/wiki-progress.php --phase=1    limit to one phase
 *     php tools/wiki-progress.php --write      regenerate wiki-content/TRACKER.md
 *
 * States: not started (no file) / draft (file exists, status: draft)
 *         / published (status: published, i.e. reviewed and live).
 */

require_once __DIR__ . '/../data/wiki.php';
require_once __DIR__ . '/../data/wiki-plan.php';

$args   = array_slice($argv ?? [], 1);
$write  = in_array('--write', $args, true);
$todo   = in_array('--todo', $args, true);
$phaseF = null;
foreach ($args as $a) {
    if (preg_match('/^--phase=(\d)$/', $a, $m)) {
        $phaseF = (int) $m[1];
    }
}

$sections = usmlewise_wiki_sections();
$all      = usmlewise_wiki_all();
$plan     = usmlewise_wiki_plan();

// ---- Plan sanity ----
$problems = [];
$seen = [];
foreach ($plan as [$sec, $slug, $title, $phase]) {
    if (!isset($sections[$sec])) {
        $problems[] = "plan row $sec/$slug: unknown section";
    }
    if (!preg_match('/\A[a-z0-9-]+\z/', $slug)) {
        $problems[] = "plan row $sec/$slug: invalid slug";
    }
    if (isset($seen["$sec/$slug"])) {
        $problems[] = "plan row $sec/$slug: duplicated";
    }
    if (strpos($title, "\u{2014}") !== false) {
        $problems[] = "plan row $sec/$slug: title contains an em dash";
    }
    $seen["$sec/$slug"] = true;
}

// ---- Classify ----
$rows = [];
foreach ($plan as [$sec, $slug, $title, $phase]) {
    if ($phaseF !== null && $phase !== $phaseF) {
        continue;
    }
    $a = $all["$sec/$slug"] ?? null;
    $state = $a === null ? 'not started'
        : ($a['status'] === 'published' ? (usmlewise_wiki_is_reviewed($a) ? 'reviewed' : 'live, review pending') : 'draft');
    $rows[] = ['section' => $sec, 'slug' => $slug, 'title' => $title, 'phase' => $phase, 'state' => $state, 'article' => $a];
}

$unplanned = [];
foreach ($all as $key => $a) {
    if (!isset($seen[$key])) {
        $unplanned[] = $key;
    }
}

$count = function (array $list): array {
    $c = ['published' => 0, 'reviewed' => 0, 'draft' => 0, 'not started' => 0, 'total' => count($list)];
    foreach ($list as $r) {
        // 'published' counts everything live; 'reviewed' is the subset signed off by a named person.
        if ($r['state'] === 'reviewed' || $r['state'] === 'live, review pending') {
            $c['published']++;
            if ($r['state'] === 'reviewed') {
                $c['reviewed']++;
            }
        } else {
            $c[$r['state']]++;
        }
    }
    return $c;
};
$pct = fn(int $n, int $t): string => $t ? sprintf('%d%%', round($n / $t * 100)) : '0%';

$overall = $count($rows);

// ---- --todo ----
if ($todo) {
    $next = array_filter($rows, fn($r) => $r['state'] === 'not started');
    usort($next, fn($x, $y) => [$x['phase'], array_search($x['section'], array_keys($sections))] <=> [$y['phase'], array_search($y['section'], array_keys($sections))]);
    foreach ($next as $r) {
        echo "P{$r['phase']}  " . str_pad("{$r['section']}/{$r['slug']}", 58) . $r['title'] . "\n";
    }
    echo "\n" . count($next) . " page(s) not started.\n";
    exit(0);
}

// ---- --write ----
if ($write) {
    $md  = "# Wiki content tracker\n\n";
    $md .= "Generated by `php tools/wiki-progress.php --write` on " . date('Y-m-d') . ". Do not edit by hand: the plan lives in `data/wiki-plan.php`, and status is read from the article files.\n\n";
    $md .= "**Legend:** `[x]` live on the site · `[ ]` draft, not live · `[ ]` not started. Review pending means live but not yet signed off by a named reviewer.\n\n";
    $md .= "## Overall\n\n";
    $md .= "| | Pages | Share |\n|---|---|---|\n";
    $md .= "| Published | {$overall['published']} | " . $pct($overall['published'], $overall['total']) . " |\n";
    $md .= "| Draft, not live | {$overall['draft']} | " . $pct($overall['draft'], $overall['total']) . " |\n";
    $md .= "| Not started | {$overall['not started']} | " . $pct($overall['not started'], $overall['total']) . " |\n";
    $md .= "| **Total planned** | **{$overall['total']}** | |\n\n";

    $md .= "## By phase\n\n| Phase | Published | Draft | Not started | Total |\n|---|---|---|---|---|\n";
    $phaseNames = [1 => 'Phase 1: Launch set', 2 => 'Phase 2: Depth', 3 => 'Phase 3: Moat'];
    foreach ($phaseNames as $p => $name) {
        $c = $count(array_filter($rows, fn($r) => $r['phase'] === $p));
        $md .= "| $name | {$c['published']} | {$c['draft']} | {$c['not started']} | {$c['total']} |\n";
    }
    $md .= "\n## By section\n\n| Section | Published | Draft | Not started | Total |\n|---|---|---|---|---|\n";
    foreach ($sections as $slug => $s) {
        $c = $count(array_filter($rows, fn($r) => $r['section'] === $slug));
        if ($c['total']) {
            $md .= "| {$s['title']} | {$c['published']} | {$c['draft']} | {$c['not started']} | {$c['total']} |\n";
        }
    }

    foreach ($sections as $slug => $s) {
        $list = array_values(array_filter($rows, fn($r) => $r['section'] === $slug));
        if (!$list) {
            continue;
        }
        usort($list, fn($x, $y) => $x['phase'] <=> $y['phase']);
        $c = $count($list);
        $md .= "\n---\n\n## {$s['title']} ({$c['published']}/{$c['total']} published)\n\n";
        foreach ($list as $r) {
            $box  = in_array($r['state'], ['reviewed', 'live, review pending'], true) ? '[x]' : '[ ]';
            $note = $r['state'] === 'reviewed' ? 'live, reviewed' : ($r['state'] === 'live, review pending' ? 'live, review pending' : ($r['state'] === 'draft' ? 'draft, not live' : 'not started'));
            $title = $r['article'] ? $r['article']['title'] : $r['title'];
            $md .= "- $box $title · `{$r['slug']}` · phase {$r['phase']} · $note\n";
        }
    }
    if ($unplanned) {
        $md .= "\n---\n\n## Written but not in the plan\n\n";
        foreach ($unplanned as $k) {
            $md .= "- `$k`\n";
        }
    }
    file_put_contents(USMLEWISE_WIKI_DIR . '/TRACKER.md', $md);
    echo "Wrote wiki-content/TRACKER.md ({$overall['total']} planned pages).\n";
    exit($problems ? 1 : 0);
}

// ---- Default summary ----
echo "Wiki progress" . ($phaseF ? " (phase $phaseF)" : '') . ": {$overall['published']} live ({$overall['reviewed']} expert-reviewed), {$overall['draft']} draft, {$overall['not started']} not started, of {$overall['total']} planned.\n\n";
echo str_pad('Section', 26) . str_pad('Pub', 6) . str_pad('Draft', 7) . str_pad('Todo', 6) . "Total\n";
foreach ($sections as $slug => $s) {
    $c = $count(array_filter($rows, fn($r) => $r['section'] === $slug));
    if ($c['total']) {
        echo str_pad($s['title'], 26) . str_pad((string) $c['published'], 6) . str_pad((string) $c['draft'], 7) . str_pad((string) $c['not started'], 6) . $c['total'] . "\n";
    }
}
echo "\n";
foreach ([1, 2, 3] as $p) {
    if ($phaseF !== null && $phaseF !== $p) {
        continue;
    }
    $c = $count(array_filter($rows, fn($r) => $r['phase'] === $p));
    echo "Phase $p: {$c['published']} published, {$c['draft']} draft, {$c['not started']} not started ({$c['total']} total)\n";
}
if ($unplanned) {
    echo "\nWritten but not in the plan: " . implode(', ', $unplanned) . "\n";
}
foreach ($problems as $p) {
    echo "PLAN PROBLEM: $p\n";
}
exit($problems ? 1 : 0);
